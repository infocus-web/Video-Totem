const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
let browser;
(async () => {
  const portraitPath = process.argv[5];
  assert.ok(portraitPath, 'Pasá una foto de prueba con un rostro derecho como quinto argumento.');
  browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  const context = await browser.newContext({ viewport: { width: 1720, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage(), errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push({ url: request.url(), method: request.method() }));
  // This feature must work without transmitting photos or contacting an AI service.
  const url = process.argv[4] || 'http://127.0.0.1:4174', origin = new URL(url).origin;
  await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  await page.goto(url, { waitUntil: 'networkidle' });
  assert.equal(requests.some(request => /wasm|smartRotation|tflite/.test(request.url)), false, 'El detector no carga al abrir la app');
  const fixtures = await page.evaluate(async base64 => {
    const image = new Image(); image.src = 'data:image/jpeg;base64,' + base64; await image.decode();
    const scale = Math.min(1, 1600 / Math.max(image.naturalWidth, image.naturalHeight));
    const width = Math.round(image.naturalWidth * scale), height = Math.round(image.naturalHeight * scale);
    return [0, 90, 180, 270].map(rotation => {
      const canvas = document.createElement('canvas'); canvas.width = rotation % 180 ? height : width; canvas.height = rotation % 180 ? width : height;
      const ctx = canvas.getContext('2d'); ctx.translate(canvas.width / 2, canvas.height / 2); ctx.rotate(rotation * Math.PI / 180);
      ctx.drawImage(image, -width / 2, -height / 2, width, height);
      return { name: 'ROSTRO-' + rotation.toString().padStart(3, '0') + '.jpg', buffer: canvas.toDataURL('image/jpeg', 0.94).split(',')[1] };
    });
  }, fs.readFileSync(portraitPath).toString('base64'));
  const blank = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 400; canvas.height = 600; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#28743f'; ctx.fillRect(0, 0, 400, 600); return canvas.toDataURL('image/png').split(',')[1]; });
  const inputs = [...fixtures.map(item => ({ name: item.name, mimeType: 'image/jpeg', buffer: Buffer.from(item.buffer, 'base64') })), { name: 'SIN-ROSTRO.png', mimeType: 'image/png', buffer: Buffer.from(blank, 'base64') }];
  const go = name => page.getByRole('tab', { name, exact: true }).click();
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('autoreel-project-v1')));
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(inputs);
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  await go('Escenas'); await page.getByRole('button', { name: 'Individual (1 foto por escena)', exact: true }).click();
  await page.getByRole('button', { name: 'Reproducir', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
  await go('Encuadre');
  for (const label of ['Encuadre horizontal', 'Encuadre vertical', 'Zoom de la foto', 'Aplicar giro a']) await page.getByLabel(label, { exact: true }).waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('button', { name: 'Pausar', exact: true }).count(), 1, 'Abrir Encuadre conserva la reproducción');
  await page.getByLabel('Zoom de la foto', { exact: true }).focus(); await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Listo, volver a la vista previa', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Reproducir', exact: true }).count(), 1, 'Editar pausa');
  await page.getByRole('button', { name: 'Restablecer encuadre', exact: true }).click();
  await go('Textos'); await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Pausar', exact: true }).click(); await go('Encuadre');
  assert.equal(await page.getByRole('button', { name: 'Encuadrar foto', exact: true }).count(), 1);
  await page.getByLabel('Escena para encuadrar').selectOption('4');
  await page.getByRole('button', { name: '↷ Girar 90° a la derecha', exact: true }).click();
  await page.getByLabel('Aplicar giro a').selectOption('all');
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByLabel('Avance del giro inteligente').waitFor();
  await page.getByLabel('Avance del giro inteligente').waitFor({ state: 'hidden', timeout: 90000 });
  console.log('Resultado por lote:', await page.locator('[role="status"]').allTextContents());
  await page.waitForTimeout(750);
  const state = await saved(), expected = [0, 270, 180, 90, 90];
  assert.deepEqual(state.slides.map(slide => slide.photos[0].framing?.rotation || 0), expected, 'Endereza las cuatro orientaciones y conserva la foto sin rostro');
  const count = requests.filter(request => request.url.endsWith('.wasm')).length;
  assert.equal(count, 1, 'Solo descarga una variante de WASM');
  assert.ok(requests.some(request => request.url.endsWith('.tflite')));
  assert.equal(requests.some(request => request.method !== 'GET'), false, 'No envía fotos');
  await page.getByRole('button', { name: 'Listo, volver a la vista previa', exact: true }).click();
  await page.getByLabel('Zoom de la foto', { exact: true }).waitFor({ state: 'visible' });
  assert.equal(await page.getByLabel('Aplicar giro a').inputValue(), 'all', 'Listo conserva el alcance elegido');
  await page.getByLabel('Aplicar giro a').selectOption('current');
  await page.getByLabel('Escena para encuadrar').selectOption('1');
  await page.getByRole('button', { name: '↷ Girar 90° a la derecha', exact: true }).click();
  await page.getByLabel('Aplicar giro a').selectOption('current');
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByLabel('Avance del giro inteligente').waitFor({ state: 'hidden', timeout: 30000 }); await page.waitForTimeout(750);
  assert.equal((await saved()).slides[1].photos[0].framing.rotation, 270, 'El alcance actual no modifica las demás');
  await page.getByLabel('Escena para encuadrar').selectOption('0');
  await page.getByRole('button', { name: '↷ Girar 90° a la derecha', exact: true }).click();
  await page.getByLabel('Escena para encuadrar').selectOption('2');
  await page.getByRole('button', { name: '↷ Girar 90° a la derecha', exact: true }).click();
  await page.getByLabel('Aplicar giro a').selectOption('selected');
  assert.ok(await page.getByRole('button', { name: 'Giro inteligente', exact: true }).isDisabled());
  await page.getByLabel('Girar ROSTRO-000.jpg', { exact: true }).check();
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByLabel('Avance del giro inteligente').waitFor({ state: 'hidden', timeout: 30000 }); await page.waitForTimeout(750);
  assert.equal((await saved()).slides[0].photos[0].framing.rotation || 0, 0);
  assert.equal((await saved()).slides[2].photos[0].framing.rotation, 270, 'Las fotos no marcadas conservan su giro');
  const beforeCancel = await saved();
  await page.getByLabel('Aplicar giro a').selectOption('all');
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByRole('button', { name: 'Cancelar análisis', exact: true }).click();
  await page.getByText('Análisis cancelado. Se conservaron todos los giros anteriores.').waitFor();
  await page.waitForTimeout(750); assert.deepEqual((await saved()).slides, beforeCancel.slides);
  await page.route('**/models/*.tflite', route => route.abort());
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByText('No se pudo analizar el giro. Se conservaron las fotos. Reintentá o usá los botones de giro manual.').waitFor({ timeout: 30000 });
  assert.ok(await page.getByRole('button', { name: 'Giro inteligente', exact: true }).isEnabled());
  await page.waitForTimeout(750); assert.deepEqual((await saved()).slides, beforeCancel.slides, 'Un error de modelo conserva el montaje');
  await page.unroute('**/models/*.tflite');
  await page.getByRole('button', { name: 'Giro inteligente', exact: true }).click();
  await page.getByLabel('Avance del giro inteligente').waitFor({ state: 'hidden', timeout: 30000 });
  await page.waitForTimeout(750); assert.deepEqual((await saved()).slides.map(slide => slide.photos[0].framing?.rotation || 0), expected, 'Se puede reintentar después de un error');
  assert.equal(requests.some(request => request.method !== 'GET'), false);
  assert.equal(requests.some(request => /^https?:/.test(request.url) && new URL(request.url).origin !== origin), false);
  await page.screenshot({ path: 'artifacts/smart-rotation-panel.png' });
  assert.deepEqual(errors, []);
  fs.writeFileSync('artifacts/smart-rotation-report.json', JSON.stringify({ status: 'passed', actualFaceModel: true, expandedControls: true, expected, cancellation: true, localOnly: true, errors }, null, 2));
  console.log('PASS: controles visibles, pausa/reanudación, rostros 0/90/180/270, sin rostro, alcance, cancelación y procesamiento local.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
