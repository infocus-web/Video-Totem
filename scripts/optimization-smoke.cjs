const { chromium } = require(process.argv[2] || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
let browser, page;
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}), args: ['--autoplay-policy=no-user-gesture-required'] });
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const tab = name => page.getByRole('tab', { name, exact: true }).click();
  const errors = [], scripts = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => {
    if (response.status() >= 400) errors.push(response.status() + ' ' + response.url());
    if (response.url().endsWith('.js')) scripts.push(response.url());
  });
  await page.addInitScript(() => {
    window.metrics = { decodes: 0, frames: 0 };
    const decode = HTMLImageElement.prototype.decode;
    HTMLImageElement.prototype.decode = function () { window.metrics.decodes++; return decode.call(this); };
    const raf = window.requestAnimationFrame;
    window.requestAnimationFrame = callback => raf.call(window, now => { window.metrics.frames++; callback(now); });
  });
  await page.goto(process.argv[4] || 'http://127.0.0.1:4173', { waitUntil: 'networkidle' });
  assert.ok(!scripts.some(url => /TimelineView-|PremiereInspectorModal-|ExportModal-|FaqGuideModal-/.test(url)), 'Las herramientas secundarias no se descargan al abrir');
  const files = (await page.evaluate(() => ['#db2777', '#4f46e5', '#059669', '#ea580c'].map((color, index) => {
    const canvas = document.createElement('canvas'); canvas.width = 1200; canvas.height = 800;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = color; ctx.fillRect(0, 0, 1200, 800);
    return { name: 'IMG_00' + (index + 1) + '.jpg', data: canvas.toDataURL('image/jpeg').split(',')[1] };
  }))).map(item => ({ name: item.name, mimeType: 'image/jpeg', buffer: Buffer.from(item.data, 'base64') }));
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(files.slice(0, 3));
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  await tab('Escenas');
  await page.getByRole('button', { name: /Individual \(1 foto por escena\)/ }).click();
  await tab('Ritmo');
  await page.getByLabel('Duración de las escenas').press('End');
  const initialDecodes = await page.evaluate(() => window.metrics.decodes);
  assert.equal(initialDecodes, 6, 'Cada foto se decodifica al importar y una vez para la vista previa');
  await page.evaluate(() => { window.metrics.frames = 0; }); await page.waitForTimeout(350);
  const idleFrames = await page.evaluate(() => window.metrics.frames);
  assert.equal(idleFrames, 0, 'La vista previa pausada no ejecuta animación');
  await page.getByLabel('Posición del video').fill('2');
  await tab('Textos');
  await page.getByLabel('Título', { exact: true }).fill('Boda de prueba');
  assert.equal(Number(await page.getByLabel('Posición del video').inputValue()), 2, 'Editar conserva la posición pausada');
  await page.getByRole('button', { name: 'Reproducir', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('[aria-label="Posición del video"]').value) > 2.2);
  const staysPlaying = async action => {
    await action();
    await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => window.metrics.decodes), initialDecodes, 'Editar no vuelve a decodificar fotos');
  };
  await staysPlaying(() => page.getByLabel('Título', { exact: true }).fill('Título editado en vivo'));
  await staysPlaying(() => page.getByLabel('Marca de agua', { exact: true }).fill('@fotografo'));
  await tab('Música');
  await staysPlaying(() => page.getByLabel('Volumen', { exact: true }).press('Home'));
  await tab('Formato');
  await staysPlaying(() => page.getByLabel('FPS', { exact: true }).selectOption('24'));
  await tab('Encuadre');
  await staysPlaying(() => page.getByRole('button', { name: /Rellenar cuadro \(recortar\)/ }).click());
  await tab('Escenas');
  await staysPlaying(() => page.getByRole('button', { name: '0px', exact: true }).click());
  await page.getByRole('button', { name: 'Línea de tiempo', exact: true }).click();
  await staysPlaying(() => page.getByLabel('Transición escena 1').selectOption('wipe'));
  await staysPlaying(() => page.getByLabel('Movimiento IMG_001.jpg').selectOption('pan-up'));
  await staysPlaying(() => page.getByLabel('Duración escena 1').fill('4'));
  await staysPlaying(() => page.getByTitle('Mover a la derecha').first().click());
  await page.getByRole('button', { name: 'Editor', exact: true }).click();
  await tab('Escenas');
  await staysPlaying(() => page.getByRole('button', { name: /2 en 1 \(Arriba y Abajo\)/ }).click());
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await page.waitForTimeout(100);
  await page.evaluate(() => { window.metrics.frames = 0; }); await page.waitForTimeout(350);
  assert.equal(await page.evaluate(() => window.metrics.frames), 0, 'El bucle se detiene al pausar');
  await tab('Fotos');
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles([files[3]]);
  await page.getByText('4 fotos conectadas', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Usar todas las fotos', exact: true }).click();
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  const afterAdding = await page.evaluate(() => window.metrics.decodes);
  assert.equal(afterAdding, initialDecodes + 2, 'Solo la foto nueva se decodifica para la vista previa');
  assert.equal(await page.getByRole('button', { name: 'Inspector XML', exact: true }).count(), 1);
  assert.equal(await page.getByRole('button', { name: 'Cómo usar AutoReel', exact: true }).count(), 1);
  assert.equal(await page.getByRole('button', { name: /^Grabar (MP4|WEBM)$/ }).count(), 0);
  await page.getByRole('button', { name: 'Cómo usar AutoReel', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'visible' });
  assert.ok(scripts.some(url => /FaqGuideModal-/.test(url)), 'La ayuda se descarga al abrirla');
  await page.keyboard.press('Escape');
  const download = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Guardar proyecto JSON' }).click()]).then(([value]) => value);
  await download.saveAs('artifacts/optimization-project.json');
  const saved = JSON.parse(fs.readFileSync('artifacts/optimization-project.json', 'utf8'));
  assert.equal(saved.config.photoFit, 'cover'); saved.slides[0].transition = 'fade';
  await page.getByLabel('Abrir proyecto', { exact: true }).setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) });
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(files);
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Línea de tiempo', exact: true }).click();
  assert.equal(await page.getByLabel('Transición escena 1').inputValue(), 'dissolve', 'Fade de proyectos antiguos aparece como Fundido');
  assert.equal(await page.getByRole('option', { name: 'Fundido', exact: true }).count(), saved.slides.length);
  await page.getByRole('button', { name: 'Editor', exact: true }).click();
  await page.evaluate(() => scrollTo(0, 0)); await page.screenshot({ path: 'artifacts/optimization-desktop.png', fullPage: true });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordes a ' + width + 'px');
  }
  await page.screenshot({ path: 'artifacts/optimization-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  fs.writeFileSync('artifacts/optimization-report.json', JSON.stringify({ status: 'passed', initialDecodes, decodesAfterAdding: afterAdding, idleFrames, playingEdits: 'passed', lazyTools: 'passed', legacyFade: 'passed', consoleErrors: errors }, null, 2));
  console.log('PASS: reproducción durante ajustes, caché de fotos, cero animación pausada, carga diferida, JSON antiguo y móvil');
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (page) await page.screenshot({ path: 'artifacts/optimization-error.png', fullPage: true }).catch(() => {});
  if (browser) await browser.close(); process.exit(1);
});
