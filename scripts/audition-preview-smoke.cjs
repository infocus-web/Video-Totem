const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
let browser;
const tone = seconds => {
  const rate = 22050, buffer = Buffer.alloc(44 + seconds * rate * 2);
  buffer.write('RIFF'); buffer.writeUInt32LE(buffer.length - 8, 4); buffer.write('WAVEfmt ', 8);
  buffer.writeUInt32LE(16, 16); buffer.writeUInt16LE(1, 20); buffer.writeUInt16LE(1, 22);
  buffer.writeUInt32LE(rate, 24); buffer.writeUInt32LE(rate * 2, 28); buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34); buffer.write('data', 36); buffer.writeUInt32LE(buffer.length - 44, 40);
  for (let i = 0; i < rate * seconds; i++) buffer.writeInt16LE(Math.round(Math.sin(i / rate * 440 * Math.PI * 2) * 8000), 44 + i * 2);
  return buffer;
};
(async () => {
  browser = await chromium.launch({ headless: true, executablePath: process.argv[3], args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.audioStarts = []; window.previewCounters = [];
    const start = AudioBufferSourceNode.prototype.start, text = CanvasRenderingContext2D.prototype.fillText;
    AudioBufferSourceNode.prototype.start = function(...args) { window.audioStarts.push({ offset: args[1], duration: args[2], loop: this.loop }); return start.apply(this, args); };
    CanvasRenderingContext2D.prototype.fillText = function(...args) { if (this.canvas.getAttribute('aria-label') === 'Vista previa del montaje') window.previewCounters.push(String(args[0])); return text.apply(this, args); };
  });
  await page.goto(process.argv[4] || 'http://127.0.0.1:4176/', { waitUntil: 'networkidle' });
  const photos = await page.evaluate(() => ['#ff0000', '#00ff00', '#0000ff'].map(color => {
    const canvas = document.createElement('canvas'); canvas.width = 960; canvas.height = 540;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = color; ctx.fillRect(0, 0, 960, 540);
    return canvas.toDataURL('image/jpeg').split(',')[1];
  }));
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(photos.map((data, index) => ({ name: `IMG_00${index + 1}.jpg`, mimeType: 'image/jpeg', buffer: Buffer.from(data, 'base64') })));
  const tab = name => page.getByRole('tab', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Reproducir', exact: true }).waitFor();
  await tab('Escenas'); await page.getByRole('button', { name: 'Individual (1 foto por escena)', exact: true }).click();
  await tab('Entrada'); await page.getByLabel('Activar entrada de quince').check();
  await page.getByLabel('Cargar canción de entrada', { exact: true }).setInputFiles({ name: 'prueba.wav', mimeType: 'audio/wav', buffer: tone(20) });
  await page.getByText('prueba.wav · 20.0s', { exact: true }).waitFor();
  await page.getByLabel('Escucha automática al mover').uncheck();
  await page.getByLabel('Inicio de música en segundos').fill('3');
  await page.waitForTimeout(100);
  assert.equal(Number(await page.getByLabel('Posición del video', { exact: true }).inputValue()), 0, 'Al cambiar el inicio del recorte, la foto queda en el comienzo del video');
  await page.getByLabel('Final de música en segundos').fill('18');
  await page.getByLabel('Inicio del contador', { exact: true }).fill('12');
  await page.getByLabel('Golpes desde segundo').fill('7');
  await page.getByLabel('Tiempos de los cortes').fill('7, 8, 9, 10, 11');
  await page.getByRole('button', { name: 'Aplicar tiempos de cortes', exact: true }).click();
  const video = page.getByLabel('Posición del video', { exact: true });
  const audio = page.getByLabel('Posición de escucha de la canción');
  const canvas = page.getByLabel('Vista previa del montaje', { exact: true });
  const pixels = () => canvas.evaluate(c => c.toDataURL());
  await video.fill('9.2'); await page.waitForTimeout(150); const expectedCounterFrame = await pixels();
  await video.fill('0'); await page.waitForTimeout(150);
  await audio.fill('12.2'); await page.waitForTimeout(150);
  assert.ok(Math.abs(Number(await video.inputValue()) - 9.2) < 0.001, 'Convierte segundos de canción a segundos del video recortado');
  assert.equal(await pixels(), expectedCounterFrame, 'Seek musical muestra el mismo contador y foto que el render del montaje');
  await page.evaluate(() => { window.previewCounters = []; });
  await audio.fill('6.8'); const initial = await pixels();
  await page.getByRole('button', { name: 'Escuchar selección de música', exact: true }).click();
  await page.waitForTimeout(1300);
  assert.notEqual(await pixels(), initial, 'Las fotos cambian al golpe durante Escuchar');
  const songTime = Number(await audio.inputValue()), movieTime = Number(await video.inputValue());
  assert.ok(Math.abs(movieTime - (songTime - 3)) < 0.15, 'Vista previa sigue el reloj de audio, sin segundo reproductor');
  assert.equal(await page.evaluate(() => window.audioStarts.length), 1, 'Escuchar inicia una sola fuente de audio');
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await page.getByRole('button', { name: 'Escuchar selección de música', exact: true }).waitFor();
  const paused = await video.inputValue(), still = await pixels(); await page.waitForTimeout(250);
  assert.equal(await video.inputValue(), paused); assert.equal(await pixels(), still, 'Pausa conserva el fotograma');
  await audio.focus(); await page.keyboard.press('Space');
  await page.getByRole('button', { name: 'Detener escucha de música', exact: true }).waitFor();
  await page.waitForTimeout(250); await page.keyboard.press('Space');
  assert.ok(Number(await video.inputValue()) > Number(paused), 'Espacio retoma audio e imágenes juntos');
  await audio.fill('12.2'); await page.keyboard.press('Space');
  await page.waitForTimeout(1150); await page.keyboard.press('Space');
  assert.ok(await page.evaluate(() => window.previewCounters.includes('5') && window.previewCounters.includes('4')), 'Contador progresa durante la prueba musical');
  await page.getByLabel('Escucha automática al mover').check();
  await audio.fill('6');
  await page.getByRole('button', { name: 'Detener escucha de música', exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => { const last = window.audioStarts.at(-1); return { offset: last.offset, duration: last.duration }; }), { offset: 6, duration: 12 }, 'Autoescucha programa el resto del recorte, sin límite de tres segundos');
  await page.waitForTimeout(4100);
  assert.ok(await page.getByRole('button', { name: 'Detener escucha de música', exact: true }).isVisible(), 'Audio e imágenes siguen reproduciéndose después de tres segundos');
  assert.ok(Number(await audio.inputValue()) > 9.8);
  assert.ok(Math.abs(Number(await video.inputValue()) - (Number(await audio.inputValue()) - 3)) < 0.15, 'Autoescucha mantiene sincronizados audio y montaje');
  await audio.focus(); await page.keyboard.press('Space');
  await page.getByRole('button', { name: 'Escuchar selección de música', exact: true }).waitFor();
  const autoPaused = await video.inputValue(); await page.waitForTimeout(250);
  assert.equal(await video.inputValue(), autoPaused, 'Espacio pausa la Autoescucha continua');
  await audio.fill('15');
  await page.getByRole('button', { name: 'Detener escucha de música', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Escuchar selección de música', exact: true }).waitFor({ timeout: 6000 });
  assert.ok(Math.abs(Number(await video.inputValue()) - 15) < 0.01, 'Autoescucha termina en el final del video recortado');
  assert.ok(await page.evaluate(() => window.previewCounters.includes('0')), 'Muestra cero al terminar el contador');
  await audio.fill('6'); await page.getByRole('button', { name: 'Detener escucha de música', exact: true }).waitFor();
  await tab('Fotos'); await page.getByRole('button', { name: 'Reproducir', exact: true }).waitFor();
  const afterTab = await video.inputValue(); await page.waitForTimeout(250); assert.equal(await video.inputValue(), afterTab, 'Cambiar de panel detiene audio e imágenes');
  assert.deepEqual(errors, []);
  console.log('Audio + fotos, seek recortado, golpes, contador, autoescucha, pausa, Espacio y cambio de panel: OK');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
