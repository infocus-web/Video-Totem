const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
let browser, page;
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.argv[4] || 'http://127.0.0.1:4174', { waitUntil: 'networkidle' });
  const data = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 800; canvas.height = 1200;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#7c3aed'; ctx.fillRect(0, 0, 800, 1200);
    return canvas.toDataURL('image/jpeg').split(',')[1];
  });
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(['ANTO-54.jpg', 'ANTO-55.jpg'].map(name => ({ name, mimeType: 'image/jpeg', buffer: Buffer.from(data, 'base64') })));
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  await page.getByLabel('Nombre del proyecto', { exact: true }).fill('Anto anterior');
  await page.getByLabel('Formato', { exact: true }).selectOption('totem-90');
  await page.getByLabel('Título', { exact: true }).fill('Texto anterior');
  await page.getByRole('button', { name: 'Encuadrar foto', exact: true }).click();
  await page.getByLabel('Zoom de la foto').fill('1.5');
  const open = () => page.getByRole('button', { name: 'Nuevo proyecto', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Nuevo proyecto', exact: true });
  await open();
  const name = dialog.getByLabel('Nombre del nuevo proyecto');
  await name.waitFor();
  assert.ok(await name.evaluate(input => document.activeElement === input), 'El nombre recibe el foco');
  await name.fill('Cancelado');
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(await page.getByLabel('Nombre del proyecto', { exact: true }).inputValue(), 'Anto anterior');
  assert.equal(await page.getByLabel('Zoom de la foto').inputValue(), '1.5', 'Cancelar conserva el encuadre');
  await open(); await name.press('Escape');
  assert.equal(await page.getByLabel('Nombre del proyecto', { exact: true }).inputValue(), 'Anto anterior');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('autoreel-project-v1')).config.name === 'Anto anterior');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('alert').filter({ hasText: 'ANTO-54.jpg' }).waitFor();
  await open(); await name.fill('   ');
  assert.ok(await dialog.getByRole('button', { name: 'Crear proyecto', exact: true }).isDisabled(), 'El nombre no acepta solo espacios');
  await name.fill('  Aylu TV  ');
  const desktopBox = await dialog.boundingBox();
  assert.ok(Math.abs(desktopBox.x + desktopBox.width / 2 - 720) < 2 && Math.abs(desktopBox.y + desktopBox.height / 2 - 450) < 2, 'La ventana aparece centrada');
  await page.screenshot({ path: 'artifacts/new-project-dialog.png' });
  const [backup] = await Promise.all([page.waitForEvent('download'), dialog.getByRole('button', { name: 'Crear proyecto', exact: true }).click()]);
  await backup.saveAs('artifacts/new-project-backup.json');
  const previous = JSON.parse(fs.readFileSync('artifacts/new-project-backup.json', 'utf8'));
  assert.equal(previous.config.name, 'Anto anterior'); assert.equal(previous.slides[0].photos[0].framing.zoom, 1.5);
  const current = await page.evaluate(() => JSON.parse(localStorage.getItem('autoreel-project-v1')));
  assert.equal(current.config.name, 'Aylu TV'); assert.equal(current.library.length, 0); assert.equal(current.slides.length, 0);
  assert.equal(current.config.eventTitle, ''); assert.equal(current.config.outputRotation, 0);
  await page.getByText('Tu próximo reel empieza acá', { exact: true }).waitFor();
  assert.equal(await page.getByRole('alert').count(), 0, 'No quedan errores de las fotos anteriores');
  assert.ok(!(await page.locator('body').innerText()).includes('ANTO-54.jpg'));
  assert.ok(!(await page.locator('body').innerText()).includes('Hay 2 fotos guardadas sin conectar'));
  assert.equal(await page.getByRole('button', { name: 'Restablecer encuadre', exact: true }).count(), 0);
  assert.equal(await page.getByLabel('Posición del video').inputValue(), '0');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel('Nombre del proyecto', { exact: true }).inputValue(), 'Aylu TV', 'El nuevo proyecto sobrevive una recarga');
  assert.equal(await page.getByRole('alert').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await open(); await name.fill('Segundo proyecto');
  const box = await dialog.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 390, 'La ventana cabe en el celular');
  await name.press('Enter'); await dialog.waitFor({ state: 'hidden' });
  assert.equal(await page.getByLabel('Nombre del proyecto', { exact: true }).inputValue(), 'Segundo proyecto');
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles({ name: 'NUEVA.jpg', mimeType: 'image/jpeg', buffer: Buffer.from(data, 'base64') });
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  assert.equal(await page.getByRole('alert').count(), 0, 'El nuevo proyecto carga sus propias fotos');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('autoreel-project-v1')).slides.length === 1);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('alert').filter({ hasText: 'NUEVA.jpg' }).waitFor();
  await page.getByRole('button', { name: 'Línea de tiempo', exact: true }).click();
  await page.getByTitle('Eliminar escena', { exact: true }).click();
  await page.getByText('Tu próximo reel empieza acá', { exact: true }).waitFor();
  assert.equal(await page.getByRole('alert').count(), 0, 'Vaciar el montaje también limpia el error sin cambiar de proyecto');
  assert.deepEqual(errors, []);
  fs.writeFileSync('artifacts/new-project-report.json', JSON.stringify({ status: 'passed', naming: true, cancelPreservesEdits: true, backupPreservesEdits: true, staleErrorCleared: true, immediatePersistence: true, mobile: true, errors }, null, 2));
  console.log('PASS: nombre, Cancelar/Escape, respaldo, limpieza del aviso ANTO, recarga, Enter y carga de nuevas fotos');
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (page) await page.screenshot({ path: 'artifacts/new-project-error.png' }).catch(() => {});
  if (browser) await browser.close(); process.exit(1);
});
