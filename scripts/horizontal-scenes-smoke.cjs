const { chromium } = require(process.argv[2] || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
let browser;
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.argv[4] || 'http://127.0.0.1:4174', { waitUntil: 'networkidle' });
  const colors=[[223,53,72],[53,187,104],[55,109,219]];
  const fixtures=await page.evaluate(colors=>colors.map(color=>{
    const canvas=document.createElement('canvas');canvas.width=600;canvas.height=1200;
    const ctx=canvas.getContext('2d');ctx.fillStyle=`rgb(${color.join(',')})`;ctx.fillRect(0,0,600,1200);
    return canvas.toDataURL('image/jpeg').split(',')[1];
  }),colors);
  const tab=name=>page.getByRole('tab',{name,exact:true});
  await tab('Formato').click();await page.getByLabel('Formato',{exact:true}).selectOption('1920x1080');
  await tab('Escenas').click();await page.getByRole('button',{name:'3 en 1 (Lado a lado)',exact:true}).click();
  await tab('Fotos').click();await page.getByLabel('Elegir fotos',{exact:true}).setInputFiles(fixtures.map((base64,index)=>({name:`VERT_${index+1}.jpg`,mimeType:'image/jpeg',buffer:Buffer.from(base64,'base64')})));
  await page.getByRole('button',{name:'Reproducir',exact:true}).waitFor();
  await page.getByText('3 fotos',{exact:true}).waitFor();await page.getByText('1 escenas',{exact:true}).waitFor();
  await tab('Ritmo').click();await page.getByLabel('Duración de las escenas').press('Home');
  await page.getByRole('button',{name:'Línea de tiempo',exact:true}).click();
  for(let i=1;i<=3;i++)await page.getByLabel('Movimiento VERT_'+i+'.jpg',{exact:true}).selectOption('static');
  const thumbnails=page.locator('[class*="group/item"]');
  assert.equal(await thumbnails.count(),3);
  assert.equal(await thumbnails.first().evaluate(element=>getComputedStyle(element.parentElement).flexDirection),'row');
  await page.getByRole('button',{name:'Editor',exact:true}).click();
  await tab('Encuadre').click();await page.getByRole('button',{name:'Rellenar cuadro (recortar)',exact:true}).click();
  const canvas=page.getByLabel('Vista previa del montaje',{exact:true});
  const pixels=()=>canvas.evaluate(canvas=>{
    const ctx=canvas.getContext('2d');return [0.2,0.5,0.8].flatMap(y=>[1/6,0.5,5/6].map(x=>Array.from(ctx.getImageData(Math.floor(x*canvas.width),Math.floor(y*canvas.height),1,1).data).slice(0,3)));
  });
  const check=(actual,expected)=>actual.forEach((rgb,index)=>rgb.forEach((value,channel)=>assert.ok(Math.abs(value-expected[index][channel])<35,JSON.stringify({actual,expected}))));
  check(await pixels(),[...colors,...colors,...colors]);
  await page.getByRole('button',{name:'Encuadrar foto',exact:true}).click();
  const bounds=await canvas.boundingBox();
  await page.mouse.click(bounds.x+bounds.width*5/6,bounds.y+bounds.height*0.5);
  assert.equal(await page.getByRole('button',{name:'Foto 3',exact:true}).getAttribute('aria-pressed'),'true');
  const border=page.locator('.preview-screen > div.pointer-events-none.border-2');
  const highlighted=await border.boundingBox();
  assert.ok(highlighted.x>bounds.x+bounds.width*0.6);assert.ok(highlighted.width<bounds.width*0.35);
  await page.mouse.move(bounds.x+bounds.width*0.5,bounds.y+bounds.height*0.5);await page.mouse.down();
  await page.mouse.move(bounds.x+bounds.width*0.5,bounds.y+bounds.height*0.5+18,{steps:5});await page.mouse.up();
  assert.equal(await page.getByRole('button',{name:'Foto 2',exact:true}).getAttribute('aria-pressed'),'true');
  assert.notEqual(await page.getByLabel('Encuadre vertical',{exact:true}).inputValue(),'50');
  await page.getByRole('button',{name:'Restablecer encuadre',exact:true}).click();
  await page.screenshot({path:'artifacts/horizontal-columns-framing.png'});
  await page.getByRole('button',{name:'Listo, volver a la vista previa',exact:true}).click();
  const exported=async name=>{
    await page.getByRole('button',{name:/Exportar \(/}).click();
    const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Grabar y descargar video',exact:true}).click()]);
    const file='artifacts/'+name+'.mp4';await download.saveAs(file);return fs.readFileSync(file).toString('base64');
  };
  const decode=base64=>page.evaluate(async base64=>{
    const url=URL.createObjectURL(new Blob([Uint8Array.from(atob(base64),char=>char.charCodeAt(0))],{type:'video/mp4'}));
    const video=document.createElement('video');video.src=url;video.muted=true;
    await new Promise((resolve,reject)=>{video.onloadeddata=resolve;video.onerror=reject;});
    video.currentTime=0.1;await new Promise(resolve=>{video.onseeked=resolve;});
    await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
    const canvas=document.createElement('canvas');canvas.width=video.videoWidth;canvas.height=video.videoHeight;
    const ctx=canvas.getContext('2d');ctx.drawImage(video,0,0);
    const pixels=[0.2,0.5,0.8].flatMap(y=>[1/6,0.5,5/6].map(x=>Array.from(ctx.getImageData(Math.floor(x*canvas.width),Math.floor(y*canvas.height),1,1).data).slice(0,3)));
    URL.revokeObjectURL(url);return {width:canvas.width,height:canvas.height,pixels};
  },base64);
  const horizontal=await decode(await exported('horizontal-columns'));
  assert.equal(horizontal.width,1920);assert.equal(horizontal.height,1080);check(horizontal.pixels,[...colors,...colors,...colors]);
  // Tótem uses the upright composition, then rotates the complete frame clockwise.
  await tab('Formato').click();await page.getByLabel('Formato',{exact:true}).selectOption('totem-90');
  await page.getByRole('button',{name:'Línea de tiempo',exact:true}).click();
  assert.equal(await thumbnails.first().evaluate(element=>getComputedStyle(element.parentElement).flexDirection),'column');
  await page.getByRole('button',{name:'Editor',exact:true}).click();
  const totem=await decode(await exported('horizontal-columns-totem'));
  check(totem.pixels,[...colors.toReversed(),...colors.toReversed(),...colors.toReversed()]);
  assert.equal(totem.width,1920);assert.equal(totem.height,1080);
  assert.deepEqual(errors,[]);
  fs.writeFileSync('artifacts/horizontal-scenes-report.json',JSON.stringify({horizontal,totem,framing:true,thumbnailOrientation:true,errors},null,2));
  console.log('PASS: tres verticales en columnas, miniaturas, selección y arrastre independientes, MP4 horizontal y giro Tótem sin alterar las filas de edición.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await browser?.close();});
