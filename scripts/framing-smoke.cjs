const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
let browser, page;
(async () => {
  fs.mkdirSync('artifacts', { recursive: true });
  browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, hasTouch: true, acceptDownloads: true });
  page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.photoDecodes = 0;
    const decode = HTMLImageElement.prototype.decode;
    HTMLImageElement.prototype.decode = function () { window.photoDecodes++; return decode.call(this); };
  });
  await page.goto(process.argv[4] || 'http://127.0.0.1:4173', { waitUntil: 'networkidle' });
  const base64 = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 1200; canvas.height = 800;
    const ctx = canvas.getContext('2d'), image = ctx.createImageData(1200, 800);
    for (let y = 0; y < 800; y++) for (let x = 0; x < 1200; x++) {
      const offset = (y * 1200 + x) * 4;
      image.data[offset] = x / 1200 * 255; image.data[offset + 1] = 30; image.data[offset + 2] = y / 800 * 255; image.data[offset + 3] = 255;
    }
    ctx.putImageData(image, 0, 0); return canvas.toDataURL('image/png').split(',')[1];
  });
  const inputs = [1, 2].map(index => ({ name: 'IMG_00' + index + '.png', mimeType: 'image/png', buffer: Buffer.from(base64, 'base64') }));
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(inputs);
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  await page.getByRole('button', { name: /Individual \(1 foto por escena\)/ }).click();
  await page.getByRole('button', { name: /Rellenar cuadro \(recortar\)/ }).click();
  await page.getByRole('checkbox', { name: 'Mostrar textos', exact: true }).uncheck();
  await page.getByLabel('Música', { exact: true }).selectOption('none');
  await page.getByRole('button', { name: 'Línea de tiempo', exact: true }).click();
  await page.getByRole('button', { name: 'Todas: corte directo', exact: true }).click();
  for (const index of [1, 2]) await page.getByLabel('Movimiento IMG_00' + index + '.png').selectOption('static');
  await page.getByRole('button', { name: 'Editor', exact: true }).click();
  const initialDecodes = await page.evaluate(() => window.photoDecodes);
  const canvas = page.getByLabel('Vista previa del montaje', { exact: true });
  const center = () => canvas.evaluate(canvas => Array.from(canvas.getContext('2d').getImageData(canvas.width / 2, canvas.height / 2, 1, 1).data).slice(0, 3));
  assert.ok(Math.abs((await center())[0] - 128) < 3);
  await page.getByRole('button', { name: 'Encuadrar foto', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  const bounds = await canvas.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width + 300, bounds.y + bounds.height / 2, { steps: 12 }); await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Encuadre horizontal"]').value === '0');
  assert.ok(Math.abs((await center())[0] - 48) < 3, 'Arrastrar mueve la foto y muestra el borde izquierdo');
  await page.getByLabel('Zoom de la foto').press('Home');
  for (let i = 0; i < 10; i++) await page.getByLabel('Zoom de la foto').press('ArrowRight');
  await page.getByLabel('Encuadre vertical', { exact: true }).press('Home');
  for (let i = 0; i < 80; i++) await page.getByLabel('Encuadre vertical', { exact: true }).press('ArrowRight');
  assert.ok(Math.abs((await center())[2] - 153) < 3);
  await canvas.focus(); await canvas.press('ArrowLeft');
  assert.equal(await page.getByLabel('Encuadre horizontal', { exact: true }).inputValue(), '2');
  await page.getByLabel('Encuadre horizontal', { exact: true }).press('Home');
  assert.equal(await page.evaluate(() => window.photoDecodes), initialDecodes, 'Encuadrar no vuelve a decodificar imágenes');
  await page.waitForTimeout(750);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('autoreel-project-v1')));
  assert.deepEqual(saved.slides[0].photos[0].framing, { x: 0, y: 0.8, zoom: 1.5 });
  assert.equal(saved.slides[1].photos[0].framing, undefined, 'No mueve otra foto');
  await page.screenshot({ path: 'artifacts/framing-desktop.png', fullPage: true });
  await page.reload();
  await page.getByLabel('Elegir fotos', { exact: true }).setInputFiles(inputs);
  await page.getByRole('button', { name: 'Reproducir vista previa', exact: true }).waitFor();
  const afterReconnect = await center();
  assert.ok(Math.abs(afterReconnect[0] - 32) < 3 && Math.abs(afterReconnect[2] - 153) < 3, 'Reconectar conserva posición y zoom');
  await page.getByRole('button', { name: 'Reproducir', exact: true }).click();
  await page.getByRole('button', { name: 'Encuadrar foto', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Reproducir', exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Listo, volver a la vista previa', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await page.getByLabel('Posición del video').press('Home');
  // Render the actual download and inspect its decoded pixels, not just the canvas.
  await page.getByLabel('Duración de las escenas').press('Home');
  for (let i = 0; i < 4; i++) await page.getByLabel('Duración de las escenas').press('ArrowRight');
  await page.getByRole('button', { name: /Exportar \(/ }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Grabar y descargar video' }).click()]);
  const path = 'artifacts/framing-video.' + download.suggestedFilename().split('.').pop(); await download.saveAs(path);
  const metadata = await page.evaluate(async ({ base64, mime }) => {
    const url = URL.createObjectURL(new Blob([Uint8Array.from(atob(base64), char => char.charCodeAt(0))], { type: mime }));
    const video = document.createElement('video'); video.src = url;
    await new Promise((resolve, reject) => { video.onloadeddata = resolve; video.onerror = reject; });
    video.currentTime = 0.15; await new Promise(resolve => { video.onseeked = resolve; });
    const canvas = document.createElement('canvas'); canvas.width = video.videoWidth; canvas.height = video.videoHeight;
    const ctx = canvas.getContext('2d'); ctx.drawImage(video, 0, 0);
    const result = { width: canvas.width, height: canvas.height, center: Array.from(ctx.getImageData(canvas.width / 2, canvas.height / 2, 1, 1).data).slice(0, 3) };
    URL.revokeObjectURL(url); return result;
  }, { base64: fs.readFileSync(path).toString('base64'), mime: path.endsWith('.mp4') ? 'video/mp4' : 'video/webm' });
  assert.equal(metadata.width, 1080); assert.equal(metadata.height, 1920);
  assert.ok(Math.abs(metadata.center[0] - 32) < 15 && Math.abs(metadata.center[2] - 153) < 15, 'El video conserva el encuadre manual');
  await page.getByRole('button', { name: /2 en 1 \(Arriba y Abajo\)/ }).click();
  await page.getByRole('button', { name: 'Encuadrar foto', exact: true }).click();
  await page.getByRole('button', { name: 'Foto 2', exact: true }).click();
  await page.getByLabel('Zoom de la foto').press('End');
  await page.setViewportSize({ width: 390, height: 844 });
  await canvas.scrollIntoViewIfNeeded();
  const mobile = await canvas.boundingBox(), touch = await context.newCDPSession(page);
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: mobile.x + mobile.width / 2, y: mobile.y + mobile.height * 0.75 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: mobile.x + mobile.width / 2 + 75, y: mobile.y + mobile.height * 0.75 - 45 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForTimeout(750);
  const stacked = await page.evaluate(() => JSON.parse(localStorage.getItem('autoreel-project-v1')));
  assert.deepEqual(stacked.slides[0].photos[0].framing, { x: 0, y: 0.8, zoom: 1.5 }, 'Apilar y tocar otra foto no cambia la primera');
  assert.ok(stacked.slides[0].photos[1].framing.x < 0.5 && stacked.slides[0].photos[1].framing.y > 0.5, 'El dedo mueve solo la segunda foto');
  await page.getByRole('button', { name: 'Restablecer encuadre', exact: true }).click();
  assert.equal(await page.getByLabel('Zoom de la foto').inputValue(), '1');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordes a ' + width);
  }
  await page.screenshot({ path: 'artifacts/framing-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  fs.writeFileSync('artifacts/framing-report.json', JSON.stringify({ status: 'passed', mouse: true, touch: true, keyboard: true, persistent: true, preservedPlayback: true, metadata, errors }, null, 2));
  console.log('PASS: arrastre, teclado, zoom, reconexión, reproducción, píxeles del video exportado, fotos apiladas y táctil');
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (page) await page.screenshot({ path: 'artifacts/framing-error.png', fullPage: true }).catch(() => {});
  if (browser) await browser.close(); process.exit(1);
});
